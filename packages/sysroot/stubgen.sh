#!/usr/bin/env bash
# stubgen.sh: a bionic symbol list (libc.map.txt and the like) as what an app
# links against for one API level: a C file of empty definitions (c) and the
# version script that gives them their versions (map). sqterm's own, after
# AOSP's ndkstubgen: the same rules, in bash alone.
#
#   bash stubgen.sh c   28 arm64 libc.map.txt > libc.c
#   bash stubgen.sh map 28 arm64 libc.map.txt > libc.map
#
# A symbol is kept when it is in a public version (not *_PRIVATE or
# *_PLATFORM, not platform-only), for this architecture (no arch tag, or
# this one), introduced at or before the API level (introduced-<arch>= over
# introduced=; on the symbol, else on its version), and not only for the
# platform's own users (apex, llndk, systemapi, future).
set -euo pipefail

[ $# -eq 4 ] || { echo "usage: stubgen.sh c|map API ARCH SYMBOL-LIST" >&2; exit 2; }
mode=$1 api=$2 arch=$3 list=$4
case $mode in c | map) ;; *) echo "stubgen.sh: mode is c or map, not $mode" >&2; exit 2 ;; esac

arches=(arm arm64 x86 x86_64 riscv64)
declare -A codename=(
  [J]=16 [J-MR1]=17 [J-MR2]=18 [K]=19 [L]=21 [L-MR1]=22 [M]=23 [N]=24 [N-MR1]=25
  [O]=26 [O-MR1]=27 [P]=28 [Q]=29 [R]=30 [S]=31 [Sv2]=32 [Tiramisu]=33
  [UpsideDownCake]=34 [VanillaIceCream]=35 [Baklava]=36
)

# An API level, in $level: a number, a codename, or (a codename not known
# here: not yet released) past every level.
to_level() {
  if [[ $1 =~ ^[0-9]+$ ]]; then level=$((10#$1))
  elif [ -n "$1" ] && [ -n "${codename[$1]+x}" ]; then level=${codename[$1]}
  else level=100000; fi
}

# The tags after '#' on a line, as tag[name] = value ("" for a bare tag).
declare -A tag
read_tags() {
  tag=()
  case $1 in *'#'*) ;; *) return 0 ;; esac
  local words word
  read -r -a words <<< "${1#*#}"
  for word in "${words[@]}"; do
    case $word in
      *=*) tag[${word%%=*}]=${word#*=} ;;
      *) tag[$word]= ;;
    esac
  done
}
has() { [ -n "${tag[$1]+x}" ]; }

# Whether the tags just read leave a symbol (or version) out; $1 is the level
# it was introduced at when its own tags do not say.
left_out() {
  local t a any_arch=0
  for t in platform-only apex llndk systemapi future; do has "$t" && return 0; done
  for a in "${arches[@]}"; do has "$a" && any_arch=1; done
  [ $any_arch = 1 ] && ! has "$arch" && return 0
  level=$1
  if has "introduced-$arch"; then to_level "${tag[introduced-$arch]}"
  elif has introduced; then to_level "${tag[introduced]}"; fi
  [ "$level" -gt "$api" ]
}

re_open=$'^[ \t]*[A-Za-z0-9_.]+[ \t]*\\{'
re_close=$'^[ \t]*\\}'
re_symbol=$'^[ \t]*[A-Za-z_][A-Za-z0-9_]*[ \t]*;'

[ "$mode" = c ] && echo "/* Generated by sqterm's stubgen.sh: link-time stubs, never run. */"
in_version=0 skip_version=0 emitted_any=0 version= version_intro=0
declare -A kept
while IFS= read -r line || [ -n "$line" ]; do
  # A version opens: "NAME {", tags maybe after.
  if [[ $line =~ $re_open ]]; then
    read -r version _ <<< "$line"
    version=${version%%\{*}
    read_tags "$line"
    version_intro=0
    if has "introduced-$arch"; then to_level "${tag[introduced-$arch]}"; version_intro=$level
    elif has introduced; then to_level "${tag[introduced]}"; version_intro=$level; fi
    skip_version=0
    case $version in *_PRIVATE | *_PLATFORM) skip_version=1 ;; esac
    [ $skip_version = 0 ] && left_out 0 && skip_version=1
    in_version=1
    if [ $skip_version = 0 ] && [ "$mode" = map ]; then printf '%s {\n  global:\n' "$version"; fi
    continue
  fi
  # A version closes: "}" or "} PARENT;".
  if [ $in_version = 1 ] && [[ $line =~ $re_close ]]; then
    in_version=0
    [ $skip_version = 1 ] && continue
    if [ "$mode" = map ]; then
      [ $emitted_any = 1 ] || printf '  local:\n    *;\n'
      parent=${line#*\}}
      parent=${parent%%;*}
      parent=${parent//[$' \t']/}
      if [ -n "$parent" ] && [ -n "${kept[$parent]+x}" ]; then echo "} $parent;"; else echo "};"; fi
    fi
    kept[$version]=1
    emitted_any=1
    continue
  fi
  if [ $in_version = 1 ] && [ $skip_version = 0 ] && [[ $line =~ $re_symbol ]]; then
    read -r name _ <<< "$line"
    name=${name%%;*}
    read_tags "$line"
    left_out "$version_intro" && continue
    if [ "$mode" = map ]; then echo "    $name;"
    elif has var; then echo "int $name = 0;"
    elif has weak; then echo "__attribute__((weak)) void $name(void) {}"
    else echo "void $name(void) {}"; fi
  fi
done < "$list"
